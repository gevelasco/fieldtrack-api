-- Mock de revisión. No es una migración y no se aplica solo.
-- Esquema PostgreSQL `fieldtrack`, convenciones de terminalOps:
--   PK integer (identity), snake_case, timestamptz, club_id en cada fila de negocio,
--   archivos por storage_key (no se guarda el binario).
-- Fuera de este mock: tablero, calendario, configuración, solicitudes y permisos de portación.

CREATE SCHEMA IF NOT EXISTS fieldtrack;

-- ---------------------------------------------------------------------------
-- Core
-- ---------------------------------------------------------------------------

CREATE TABLE fieldtrack.clubs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  tagline text,
  legal_name text,
  subscription_status text NOT NULL DEFAULT 'active'
    CHECK (subscription_status IN ('active', 'suspended')),
  cuota_tiro_mxn numeric(12, 2) NOT NULL DEFAULT 2800,
  cuota_caceria_mxn numeric(12, 2) NOT NULL DEFAULT 3500,
  tiro_inicio_mes smallint NOT NULL DEFAULT 1 CHECK (tiro_inicio_mes BETWEEN 1 AND 12),
  tiro_inicio_dia smallint NOT NULL DEFAULT 1 CHECK (tiro_inicio_dia BETWEEN 1 AND 31),
  tiro_fin_mes smallint NOT NULL DEFAULT 12 CHECK (tiro_fin_mes BETWEEN 1 AND 12),
  tiro_fin_dia smallint NOT NULL DEFAULT 31 CHECK (tiro_fin_dia BETWEEN 1 AND 31),
  caza_inicio_mes smallint NOT NULL DEFAULT 6 CHECK (caza_inicio_mes BETWEEN 1 AND 12),
  caza_inicio_dia smallint NOT NULL DEFAULT 1 CHECK (caza_inicio_dia BETWEEN 1 AND 31),
  caza_fin_mes smallint NOT NULL DEFAULT 5 CHECK (caza_fin_mes BETWEEN 1 AND 12),
  caza_fin_dia smallint NOT NULL DEFAULT 31 CHECK (caza_fin_dia BETWEEN 1 AND 31),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Una cuenta pertenece a un solo club, como app_user.company_id en terminalOps.
-- Cada club tiene su propio admin. El username se repite entre clubes, no dentro del mismo.
CREATE TABLE fieldtrack.app_user (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id integer NOT NULL REFERENCES fieldtrack.clubs (id) ON DELETE CASCADE,
  username text NOT NULL,
  display_name text,
  email text,
  phone text,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('admin', 'staff', 'socio')),
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'disabled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT app_user_id_club_uidx UNIQUE (id, club_id),
  CONSTRAINT app_user_club_username_uidx UNIQUE (club_id, username),
  CONSTRAINT app_user_club_email_uidx UNIQUE (club_id, email)
);

CREATE INDEX app_user_club_id_idx ON fieldtrack.app_user (club_id);

CREATE TABLE fieldtrack.user_preferences (
  user_id integer PRIMARY KEY REFERENCES fieldtrack.app_user (id) ON DELETE CASCADE,
  theme_scheme text NOT NULL DEFAULT 'light'
    CHECK (theme_scheme IN ('light', 'dark')),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE fieldtrack.refresh_tokens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id integer NOT NULL REFERENCES fieldtrack.app_user (id) ON DELETE CASCADE,
  jti uuid NOT NULL,
  token_hash text NOT NULL,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  replaced_by_jti uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT refresh_tokens_jti_uidx UNIQUE (jti),
  CONSTRAINT refresh_tokens_token_hash_uidx UNIQUE (token_hash)
);

CREATE INDEX refresh_tokens_user_id_idx ON fieldtrack.refresh_tokens (user_id);

-- Confirmación de algo ya hecho (pago, alta, inventario, documento, PETA).
-- kind es texto libre para no migrar cada aviso nuevo.
CREATE TABLE fieldtrack.club_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id integer NOT NULL REFERENCES fieldtrack.clubs (id) ON DELETE CASCADE,
  kind text NOT NULL,
  title text NOT NULL,
  detail text NOT NULL,
  entity_type text,
  entity_id text,
  actor_user_id integer,
  CONSTRAINT club_notifications_actor_same_club_fk
    FOREIGN KEY (actor_user_id, club_id)
    REFERENCES fieldtrack.app_user (id, club_id),
  actor_label text NOT NULL DEFAULT 'Sistema',
  occurred_at timestamptz NOT NULL,
  dedupe_key text
);

CREATE INDEX club_notifications_club_occurred_idx
  ON fieldtrack.club_notifications (club_id, occurred_at DESC);

CREATE UNIQUE INDEX club_notifications_dedupe_uidx
  ON fieldtrack.club_notifications (club_id, dedupe_key)
  WHERE dedupe_key IS NOT NULL;

-- La lectura es por usuario. El cajón de la app hoy marca leídas todas las del club.
CREATE TABLE fieldtrack.club_notification_reads (
  notification_id bigint NOT NULL REFERENCES fieldtrack.club_notifications (id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES fieldtrack.app_user (id) ON DELETE CASCADE,
  read_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (notification_id, user_id)
);

-- ---------------------------------------------------------------------------
-- Socios
-- ---------------------------------------------------------------------------

-- user_id queda vacío mientras el miembro no tenga cuenta, y solo puede
-- apuntar a un usuario del mismo club.
-- ingreso no se edita después del alta: es regla de aplicación.
-- status: vetado se persiste. vigente y pendiente se recalculan con los pagos
-- del periodo de su membresía y del club.
CREATE TABLE fieldtrack.members (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id integer NOT NULL REFERENCES fieldtrack.clubs (id) ON DELETE CASCADE,
  user_id integer,
  CONSTRAINT members_user_same_club_fk
    FOREIGN KEY (user_id, club_id)
    REFERENCES fieldtrack.app_user (id, club_id),
  numero text NOT NULL,
  nombre text NOT NULL,
  apellido_paterno text NOT NULL,
  apellido_materno text NOT NULL DEFAULT '',
  correo text NOT NULL DEFAULT '',
  telefono text NOT NULL DEFAULT '',
  ingreso date NOT NULL,
  sexo text NOT NULL CHECK (sexo IN ('hombre', 'mujer', 'otro')),
  membresia text NOT NULL CHECK (membresia IN ('tiro-deportivo', 'caza')),
  status text NOT NULL DEFAULT 'vigente'
    CHECK (status IN ('vigente', 'pendiente', 'vetado')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT members_club_numero_uidx UNIQUE (club_id, numero),
  CONSTRAINT members_id_club_uidx UNIQUE (id, club_id)
);

CREATE INDEX members_club_id_idx ON fieldtrack.members (club_id);

CREATE UNIQUE INDEX members_club_user_uidx
  ON fieldtrack.members (club_id, user_id)
  WHERE user_id IS NOT NULL;

-- Solo existe la fila cuando hay archivo. Sin fila, el expediente lo muestra pendiente.
-- Los 8 slots son los del alta; no se guardan filas vacías.
CREATE TABLE fieldtrack.member_documents (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id integer NOT NULL REFERENCES fieldtrack.members (id) ON DELETE CASCADE,
  slot text NOT NULL CHECK (slot IN (
    'carta-antecedentes',
    'cartilla-militar',
    'certificado-medico',
    'comprobante-domicilio',
    'csf',
    'curp',
    'examen-psicologico',
    'ine'
  )),
  file_name text NOT NULL,
  storage_key text,
  content_type text,
  size_bytes bigint,
  loaded_at date NOT NULL,
  CONSTRAINT member_documents_slot_uidx UNIQUE (member_id, slot)
);

-- Máximo 10 armas por socio: lo impone la aplicación, no un trigger.
-- con_peta marca que esa arma está amparada. El archivo del permiso vive en member_petas.
CREATE TABLE fieldtrack.member_weapons (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id integer NOT NULL,
  member_id integer NOT NULL,
  CONSTRAINT member_weapons_member_same_club_fk
    FOREIGN KEY (member_id, club_id)
    REFERENCES fieldtrack.members (id, club_id) ON DELETE CASCADE,
  marca text NOT NULL,
  modelo text NOT NULL,
  calibre text NOT NULL,
  numero_serie text NOT NULL DEFAULT '',
  plataforma text NOT NULL CHECK (plataforma IN ('pistola', 'escopeta', 'rifle', 'otro')),
  modalidad text NOT NULL CHECK (modalidad IN (
    'proteccion-domicilio',
    'proteccion-parcela',
    'tiro-deportivo',
    'caceria'
  )),
  con_peta boolean NOT NULL DEFAULT false,
  registrada_en date NOT NULL,
  hoja_file_name text,
  hoja_storage_key text,
  hoja_content_type text,
  hoja_size_bytes bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX member_weapons_member_id_idx ON fieldtrack.member_weapons (member_id);
CREATE INDEX member_weapons_club_id_idx ON fieldtrack.member_weapons (club_id);

-- Un archivo por tipo. Reemplazar actualiza la misma fila.
CREATE TABLE fieldtrack.member_petas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id integer NOT NULL,
  member_id integer NOT NULL,
  CONSTRAINT member_petas_member_same_club_fk
    FOREIGN KEY (member_id, club_id)
    REFERENCES fieldtrack.members (id, club_id) ON DELETE CASCADE,
  tipo text NOT NULL CHECK (tipo IN ('caceria', 'tiro-competencia', 'tiro-campo')),
  file_name text NOT NULL,
  storage_key text,
  content_type text,
  size_bytes bigint,
  loaded_at date NOT NULL,
  CONSTRAINT member_petas_tipo_uidx UNIQUE (member_id, tipo)
);

CREATE INDEX member_petas_club_id_idx ON fieldtrack.member_petas (club_id);

-- cantidad queda fija aunque después cambie la cuota del club.
-- modalidad es la del cobro, no se mueve si luego cambia el alta.
CREATE TABLE fieldtrack.membership_payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id integer NOT NULL,
  member_id integer NOT NULL,
  CONSTRAINT membership_payments_member_same_club_fk
    FOREIGN KEY (member_id, club_id)
    REFERENCES fieldtrack.members (id, club_id) ON DELETE CASCADE,
  modalidad text NOT NULL CHECK (modalidad IN ('tiro-deportivo', 'caza')),
  fecha date NOT NULL,
  cantidad numeric(12, 2) NOT NULL CHECK (cantidad >= 0),
  registrado_por_user_id integer NOT NULL,
  CONSTRAINT membership_payments_actor_same_club_fk
    FOREIGN KEY (registrado_por_user_id, club_id)
    REFERENCES fieldtrack.app_user (id, club_id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX membership_payments_member_fecha_idx
  ON fieldtrack.membership_payments (member_id, fecha DESC);

CREATE INDEX membership_payments_club_id_idx
  ON fieldtrack.membership_payments (club_id);

